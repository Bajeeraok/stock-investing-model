"""Rebuild signals/market_pulse_tables.py: full-day return odds by open gap × prior VIX close.

Usage: python scripts/build_market_pulse_tables.py [start=2005-01-01]
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yfinance as yf

GAP_EDGES = [-99.0, -1.5, -0.75, -0.25, 0.25, 0.75, 1.5, 99.0]
VIX_EDGES = [0.0, 15.0, 20.0, 25.0, 30.0, 999.0]


def _daily(sym: str, start: str) -> pd.DataFrame:
    d = yf.download(sym, start=start, interval="1d", progress=False, auto_adjust=False)
    if isinstance(d.columns, pd.MultiIndex):
        d.columns = [c[0] for c in d.columns]
    return d


def _row(x: pd.Series) -> tuple:
    return (int(x.size), round(float((x < 0).mean()), 2), round(float(x.quantile(0.1)), 2),
            round(float(x.median()), 2), round(float(x.quantile(0.9)), 2))


def build(sym: str, vix: pd.Series, start: str) -> dict:
    df = _daily(sym, start)
    t = pd.DataFrame({"o": df["Open"], "c": df["Close"]}).join(vix.rename("vix"), how="inner")
    t["pc"], t["vprev"] = t["c"].shift(1), t["vix"].shift(1)
    t = t.dropna()
    t["gap"] = (t["o"] / t["pc"] - 1) * 100
    t["full"] = (t["c"] / t["pc"] - 1) * 100
    gap_rows, cells = [], {}
    for gi in range(len(GAP_EDGES) - 1):
        lo, hi = GAP_EDGES[gi], GAP_EDGES[gi + 1]
        g = t[(t["gap"] > lo) & (t["gap"] <= hi)]
        gap_rows.append((lo, hi, *_row(g["full"])))
        for vi in range(len(VIX_EDGES) - 1):
            v = g[(g["vprev"] > VIX_EDGES[vi]) & (g["vprev"] <= VIX_EDGES[vi + 1])]
            if len(v):
                cells[(gi, vi)] = _row(v["full"])
    return {"gap": gap_rows, "cells": cells, "start": str(t.index[0].date()), "end": str(t.index[-1].date())}


def main() -> None:
    start = sys.argv[1] if len(sys.argv) > 1 else "2005-01-01"
    vix = _daily("^VIX", start)["Close"]
    out = ['"""Generated by scripts/build_market_pulse_tables.py — do not edit by hand."""', ""]
    out.append(f"GAP_EDGES = {GAP_EDGES}")
    out.append(f"VIX_EDGES = {VIX_EDGES}")
    out.append("# gap rows: (gap_low, gap_high, n, p_red, q10, q50, q90); cells: (gap_i, vix_i) -> (n, p_red, q10, q50, q90)")
    out.append("TABLES = {")
    for sym in ("SPY", "QQQ"):
        b = build(sym, vix, start)
        out.append(f'    "{sym}": {{')
        out.append(f'        "period": "{b["start"][:4]}–{b["end"][:4]}",')
        out.append('        "gap": [')
        out += [f"            {r}," for r in b["gap"]]
        out.append("        ],")
        out.append('        "cells": {')
        out += [f"            {k}: {v}," for k, v in sorted(b["cells"].items())]
        out.append("        },")
        out.append("    },")
    out.append("}")
    p = Path(__file__).resolve().parents[1] / "signals" / "market_pulse_tables.py"
    p.write_text("\n".join(out) + "\n")
    print("wrote", p)


if __name__ == "__main__":
    main()
